@app.get("/health")
def health():
    """Reports what is actually loaded, not just that the process is alive.

    A health check that only returns {"ok": true} cannot distinguish a working
    service from one serving an empty or mismatched corpus.
    """
    return {
        "status": "ok",
        "articles": len(retrieval.ARTICLES),
        "vectors": list(retrieval.VECTORS.shape),
        "embedding_model": retrieval.SIDECAR["model"],
        "answer_model": llm.model_name(),
        "answer_provider": llm.provider(),
        # Deployment diagnosis without exposing the secret: an empty key is the
        # difference between "model unavailable" and "not configured at all".
        "answer_key_present": llm.key_present(),
        "edition_from": retrieval.SIDECAR["edition_from"],
        "edition_to": retrieval.SIDECAR["edition_to"],
        "edition_expired": edition.is_expired(retrieval.SIDECAR["edition_to"]),
        "edition_days_left": edition.days_left(retrieval.SIDECAR["edition_to"]),
        "threshold": gate.THRESHOLD,
        "rerank_model": retrieval.RERANK_MODEL,
        "languages": ["lt", "en"],
        "mcp": {
            "path": "/mcp",
            "transport": "streamable-http",
            "tools": ["corpus_info", "search_labour_code", "get_article",
                      "ask_labour_code"],
            "auth": (
                "oauth" if mcp_server.OAUTH
                else ("bearer" if MCP_TOKEN else "none")
            ),
        },
        "usage": limiter.stats(),
    }


def status_payload():
    """Coverage, freshness and measured quality in one place."""
    today = date.today().isoformat()
    sources = (
        json.loads((Path(__file__).parent / "data" / "sources.json").read_text(encoding="utf-8"))
        if (Path(__file__).parent / "data" / "sources.json").exists()
        else []
    )
    explanations = [r for r in sources if r.get("act_id") == "vdi-faq"]
    acts = sorted({r["source"] for r in sources if r.get("act_id") != "vdi-faq"})
    stale = sorted({
        r["source"] for r in sources
        if r.get("act_id") != "vdi-faq" and r["valid_to"] < today
    })

    quality_file = Path(__file__).parent / "data" / "quality.json"
    quality = (
        json.loads(quality_file.read_text(encoding="utf-8"))
        if quality_file.exists()
        else {}
    )

    def summary(name):
        return quality.get(name)

    return {
        "code": {
            "articles": len(retrieval.ARTICLES),
            "edition_from": retrieval.SIDECAR["edition_from"],
            "edition_to": retrieval.SIDECAR["edition_to"],
            "expired": edition.is_expired(retrieval.SIDECAR["edition_to"]),
        },
        "delegated_acts": {
            "acts": len(acts),
            "chunks": len(sources) - len(explanations),
            "stale": stale,
            "titles": acts,
        },
        "explanations": {
            "items": len({r["citation"] for r in explanations}),
            "chunks": len(explanations),
            "source": "Valstybinė darbo inspekcija",
        },
        "history": link_graph.load() and {
            "editions": history.coverage()["editions"],
            "from": history.coverage()["from"],
        },
        "links": {
            "articles_linked": link_graph.load()["articles_linked"],
            "edges": link_graph.load()["edges"],
        },
        "evals": {
            "code_served": summary("code_served"),
            "delegated": summary("delegated"),
        },
    }


