@app.post("/chat")
def chat(request: ChatRequest, http: Request):
    denied = limiter.check(ratelimit.client_ip(http))
    if denied:
        status, reason, retry_after = denied
        log.warning("blocked ip=%s reason=%s", ratelimit.client_ip(http), reason)
        return JSONResponse(
            status_code=status,
            headers={"Retry-After": str(retry_after)},
            content={
                "answer": None,
                "error": reason,
                "detail": (
                    "This is a public demo with a spending cap. "
                    "Try again later, or run it yourself: "
                    "https://github.com/dziugasmarcenas-ui/legal-rag"
                ),
                "retry_after_seconds": retry_after,
            },
        )

    results = retrieval.retrieve(request.question)
    # The gate reads the Code only: delegated acts corroborate, they do not
    # decide whether the Code answers the question.
    code_results = [r for r in results if r.get("article")]
    # report the same quantity the gate decides on, never a different one
    confidence = max((r[gate.SIGNAL] for r in code_results), default=0.0)

    # Sources are attached whether or not we answer, so a refusal still shows
    # what was considered and at what score. Refusing invisibly is not honest.
    sources = [
        {
            "article": r["article"],
            "citation": r["citation"],
            "source": r.get("source", "Darbo kodeksas"),
            "title": r["title"],
            "cosine_score": round(r["cosine_score"], 4),
            "rerank_score": round(r["rerank_score"], 4) if r["rerank_score"] is not None else None,
        }
        for r in results
    ]

    if not gate.should_answer(code_results):
        log.info("refused q_len=%d confidence=%.4f", len(request.question), confidence)
        return {
            "answer": REFUSAL[request.lang],
            "sources": sources,
            "confidence": round(confidence, 4),
            "confidence_signal": "max_" + gate.SIGNAL,
            "refused": True,
        }

    try:
        answer = generate_answer(request.question, results, request.lang)
    except llm.ProviderUnavailable as error:
        # The model API failing is not the same as having no answer. Say so,
        # and still return the retrieved sources -- they were computed locally
        # and are useful on their own.
        log.error("answer generation failed: %s", error)
        return {
            "answer": None,
            "error": "answer_generation_unavailable",
            "sources": sources,
            "confidence": round(confidence, 4),
            "confidence_signal": "max_" + gate.SIGNAL,
            "refused": False,
        }

    log.info("answered q_len=%d confidence=%.4f", len(request.question), confidence)
    return {
        "answer": answer,
        "sources": sources,
        "confidence": round(confidence, 4),
        "confidence_signal": "max_" + gate.SIGNAL,
        "refused": False,
    }


